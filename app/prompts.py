"""研究图 v0.2 提示词套件与结构化输出模型（设计源自研究仓 argus-lg v0.2，产品内重写）。

设计原则（研究仓 v02_devlog 记录）：
- 每个 prompt 内置该环节的分析方法论（尽调框架/检索策略/缺口自评/研报文体），
  不是一句话指令；
- 事实与分析分层：事实句末 [n] 引用，分析句冠「分析：」并给依据编号；
- 单次调用证据窗有界（撞墙⑤实测边界），总证据无上限由多轮消化实现；
- 备忘录内引用用〔chunk_id〕标记，写作前由代码映射为全局 [n]（编号翻译不交给 LLM）。

产品适配（相对研究仓原文，仅两处）：
- 去掉「A 股上市公司」定语——产品语料是用户任意上传的公司；
- 〔chunk_id〕示例改为产品形态（source_id = 文件名主干-sha8）。
"""

from langchain_core.prompts import ChatPromptTemplate
from pydantic import BaseModel, Field


class AspectSpec(BaseModel):
    name: str = Field(description="方面名，如：财务表现与盈利质量")
    focus: str = Field(description="该方面的研究目标，一句话")
    key_questions: list[str] = Field(
        description="3~5 个必须回答的具体问题，含年份与指标要求"
    )


class AspectPlan(BaseModel):
    aspects: list[AspectSpec] = Field(description="3~5 个研究方面")


class QueryList(BaseModel):
    queries: list[str] = Field(description="3~4 条中文检索查询")


class Reflection(BaseModel):
    done: bool = Field(description="关键问题是否已基本回答、证据是否充分")
    gaps: list[str] = Field(
        default_factory=list, description="仍未回答的缺口，每条一句"
    )
    queries: list[str] = Field(
        default_factory=list, description="针对缺口的补查查询，≤3 条；done=true 时留空"
    )
    core_chunk_ids: list[str] = Field(
        description="当前认定的核心证据 chunk_id 列表（≤24，按重要性排序）"
    )


class ReviewVerdict(BaseModel):
    need_more: bool = Field(description="是否需要补充研究")
    followups: list[AspectSpec] = Field(
        default_factory=list, description="补研任务，≤2 个；need_more=false 时留空"
    )


